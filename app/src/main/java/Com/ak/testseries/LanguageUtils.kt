@Composable
fun stringRes(english: String): String {
    val lang = LocalAppLanguage.current
    if (lang == AppLanguage.HINDI) {
        return translationMap[english] ?: english
    }
    return english
}

fun stringResNonComposable(english: String, lang: AppLanguage): String {
    if (lang == AppLanguage.HINDI) {
        return translationMap[english] ?: english
    }
    return english
}
